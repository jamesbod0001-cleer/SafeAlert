window.SafeAlertI18n.getLang = function getLang() {
  return localStorage.getItem('safealert_lang') || 'en';
};

window.t = function t(key) {
  const lang = window.SafeAlertI18n.getLang();
  const pack = window.SafeAlertI18n[lang] || window.SafeAlertI18n.en;
  return pack[key] || window.SafeAlertI18n.en[key] || key;
};

window.applyI18n = function applyI18n() {
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const k = el.getAttribute('data-i18n');
    if (!k) return;
    const text = t(k);
    if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
      if (el.hasAttribute('placeholder')) el.placeholder = text;
      return;
    }
    el.textContent = text;
    const navBtn = el.closest('.nav-item');
    if (navBtn) navBtn.setAttribute('aria-label', text);
  });
};
